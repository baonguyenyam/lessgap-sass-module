#!/usr/bin/env node
/**
 * Writes src/generated/migrations.ts: the Prisma 8 migration graph this build ships.
 *
 *   node scripts/generate-migration-manifest.mjs
 *
 * It runs before every build (the `prebuild` script), and the file it writes is
 * committed as well.
 *
 * Why it exists: /api/health reports whether the database a deployment talks to
 * is at the contract the code was built with, and how many migrations it is
 * missing if not. On a serverless host the migrations folder is not something to
 * rely on at runtime, so the graph (name, from hash, to hash of every migration
 * in migrations/app) is compiled into the build instead.
 *
 * Why the output is committed and not only generated: a checkout that has never
 * been built is still consistent, and a manifest that falls behind the folder
 * fails src/lib/migration-manifest.test.ts.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { pathToFileURL } from "node:url"
import { readMigrationGraph } from "#src/lib/migration-graph.ts"

const root = path.resolve(import.meta.dirname, "..")
const outFile = path.join(root, "src", "generated", "migrations.ts")

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const edges = readMigrationGraph(path.join(root, "migrations", "app"))
  const content = [
    "// Generated by scripts/generate-migration-manifest.mjs. Do not edit by hand:",
    "// it is rewritten before every build from migrations/app/*/migration.json.",
    "",
    'import type { MigrationEdge } from "@/lib/migration-chain"',
    "",
    "export const MIGRATIONS: readonly MigrationEdge[] = [",
    ...edges.map((e) => `  { name: "${e.name}", from: ${e.from === null ? "null" : `"${e.from}"`}, to: "${e.to}" },`),
    "]",
    "",
  ].join("\n")

  // Compared with line endings normalised, so a Windows checkout does not
  // rewrite an identical file on every build.
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : null
  if (current === content) {
    console.log(`Migration manifest up to date: ${edges.length} migration(s).`)
  } else {
    mkdirSync(path.dirname(outFile), { recursive: true })
    writeFileSync(outFile, content)
    console.log(`Migration manifest written: ${edges.length} migration(s).`)
  }
}
